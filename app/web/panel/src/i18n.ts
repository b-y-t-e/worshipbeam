const dictionaries: Record<Language, Dictionary | null> = { pl: null, en, hu, hr };

const supported = (value: string | null | undefined): Language | null => {
  const code = value?.slice(0, 2).toLowerCase();
  return LANGUAGES.find((l) => l === code) ?? null;
};

let language: Language = supported(localStorage.getItem(KEY)) ?? supported(navigator.language) ?? "pl";
document.documentElement.lang = language;
const listeners = new Set<() => void>();

/** Język z aplikacji (stan); nieznany albo brak — bez zmiany. */
export function setLanguage(value: string | null | undefined) {
  const next = supported(value);
  if (!next || next === language) return;
  language = next;
  localStorage.setItem(KEY, next);
  document.documentElement.lang = next;
  listeners.forEach((l) => l());
}

export const getLanguage = () => language;

/** Komponent odświeża się po zmianie języka (wystarczy w korzeniu — dzieci rysują się razem z nim). */
export function useLanguage(): Language {
  return useSyncExternalStore(
    (listener) => { listeners.add(listener); return () => listeners.delete(listener); },
    () => language,
  );
}

/** Tekst w bieżącym języku; klucz = tekst polski, `{0}`… = kolejne wartości. */
export function t(text: string, ...values: (string | number)[]): string {
  const translated = dictionaries[language]?.[text] ?? text;
  return values.length ? translated.replace(/\{(\d+)\}/g, (m, i: string) => (values[+i] !== undefined ? String(values[+i]) : m)) : translated;
}

/** Ustawienia regionalne do dat. */
export const locale = () => ({ pl: "pl-PL", en: "en-GB", hu: "hu-HU", hr: "hr-HR" })[language];
